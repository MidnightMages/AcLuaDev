local stepSize = 2
local callSkipCounter = 0
local function printLineSparse(s)
    callSkipCounter = callSkipCounter+1
    if callSkipCounter == stepSize then
        callSkipCounter = 0
        return
    end
    local printStr = ""
    for i = 1, #s, stepSize do
        printStr = printStr .. s:sub(i,i)
    end
    printInline(printStr.."\n")
end
